"""Write grumpy-gambling's default tables (server/default_data.lua) from the DEV database.

grumpy-gambling seeds these once into an empty database (server/defaults.lua), per group, so the paid-MLO groups can
be switched off in Config.DefaultTables. Business/player-owned tables are left out (their owners won't exist).

Usage:  python tools/export-gambling-defaults.py
Env:    CNF (read-only option file), MYSQL (client path)
"""
import json
import math
import os
import pathlib
import subprocess
from datetime import date

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "resources/[grumpy]/grumpy-gambling/server/default_data.lua"
CNF = os.environ.get("CNF", "/c/Users/cntry/.territories-db/claude_ro.cnf")
MYSQL = os.environ.get("MYSQL", "C:/xampp/mysql/bin/mysql.exe")
if CNF.startswith("/c/"):
    CNF = "C:/" + CNF[3:]

# A table inside one of these circles goes in that group; everything else is 'towns'.
# Groups that need a paid MLO get their own switch in Config.DefaultTables.Groups.
GROUPS = [
    ("casino_boat", (-662.0, -1261.0), 30.0),          # Blackwater casino boat (paid MLO)
    ("thieves_landing", (-1395.38, -2316.86), 60.0),   # C'sky Thieves Landing rebuild (paid MLO), origin from its ymap
]
COLS = ["label", "kind", "source", "model", "bound", "x", "y", "z", "h", "currency", "fixed_tier",
        "seats", "dealer", "settings", "enabled"]


def query(sql):
    out = subprocess.run([MYSQL, f"--defaults-extra-file={CNF}", "-N", "-B", "-r", "-e", sql],
                         check=True, capture_output=True, text=True, encoding="utf-8").stdout
    return [json.loads(line) for line in out.replace("\r", "").splitlines() if line.strip()]


def lua(v):
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def group_of(x, y):
    for name, (cx, cy), r in GROUPS:
        if math.hypot(x - cx, y - cy) <= r:
            return name
    return "towns"


obj = ", ".join(f"'{c}', `{c}`" for c in COLS)
tables = query(f"SELECT JSON_OBJECT('id', id, {obj}) FROM grumpy_gambling_tables "
               "WHERE business_id IS NULL AND owner_cid IS NULL ORDER BY id")
models = query("SELECT JSON_OBJECT('model', model, 'data', data) FROM grumpy_gambling_models ORDER BY model")

lines = [
    "-- GENERATED by tools/export-gambling-defaults.py from the dev database on " + date.today().isoformat() + ".",
    "-- Re-run the tool instead of editing. Seeded once by server/defaults.lua (see Config.DefaultTables).",
    "-- seats / dealer / settings / data are JSON strings, stored as-is.",
    "GG.DefaultData = {",
    "    models = {",
]
for m in models:
    lines.append(f"        {{ model = {lua(m['model'])}, data = {lua(m['data'])} }},")
lines += ["    },", "    tables = {"]
counts = {}
for t in tables:
    g = group_of(t["x"], t["y"])
    counts[g] = counts.get(g, 0) + 1
    fields = ", ".join(f"{c} = {lua(t[c])}" for c in COLS if t[c] is not None)
    lines.append(f"        {{ group = {lua(g)}, {fields} }}, -- dev id {t['id']}")
lines += ["    },", "}", ""]
OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"{OUT.relative_to(ROOT)}: {len(models)} models, {len(tables)} tables {counts}")
