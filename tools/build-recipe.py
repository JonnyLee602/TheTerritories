"""Generate recipe/territories.yaml: a step-by-step txAdmin recipe in the style of RSG's own.

  python tools/build-recipe.py

- Stock RSG resources download from Rexshack-RedM, pinned to the commit in upstream.lock.
- Resources we customized (main differs from upstream) and the grumpy scripts download from our repo, one per step.
- A pause every BATCH downloads keeps GitHub from throttling, like RSG's recipe.
Run it after every update (tools/rsg-update.sh does this for you) and commit the result.
"""
import pathlib, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPO = "https://github.com/JonnyLee602/TheTerritories"
BRANCH = "main"
FW = "resources/[framework]"
GR = "resources/[grumpy]"
BATCH = 10
FIRST = ["rsg-core", "rsg-gizmo", "rsg-inventory", "rsg-target"]  # download order only; server.cfg sets start order

STANDALONE = [
    ("https://github.com/Rexshack-RedM/ox_lib", "main", "./resources/[standalone]/ox_lib"),
    ("https://github.com/Rexshack-RedM/PolyZone", "main", "./resources/[standalone]/PolyZone"),
    ("https://github.com/Xogy/xsound", "master", "./resources/[standalone]/xsound"),
    ("https://github.com/Rexshack-RedM/interact-sound", "main", "./resources/[standalone]/interact-sound"),
    ("https://github.com/Rexshack-RedM/menu_base", "main", "./resources/[standalone]/menu_base"),
    ("https://github.com/Rexshack-RedM/rNotify", "main", "./resources/[standalone]/rNotify"),
    ("https://github.com/Popisek/redm-female-fix", "main", "./resources/[standalone]/redm-female-fix"),
]
EXTRAS = [  # RSG's recipe also pulls Nt_Blackjack + Nt_Holdem into [community]: dropped, grumpy-gambling replaces them
    ("https://github.com/Rexshack-RedM/rsg-mapping", "main", "./resources/[mapmods]/rsg-mapping"),
    ("https://github.com/Rexshack-RedM/redm-ymaps", "main", "./resources/[mapmods]/redm-ymaps"),
]


def git(*args):
    return subprocess.run(["git", "-C", str(ROOT), *args], check=True, capture_output=True, text=True).stdout


lock = {}
for line in git("show", "upstream:upstream.lock").splitlines():
    name, commit = line.split()
    if name != "txAdminRecipe":
        lock[name] = commit
on_main = {p.name for p in (ROOT / FW).iterdir() if p.is_dir()}
if set(lock) != on_main:
    sys.exit(f"upstream.lock and {FW} disagree: {sorted(set(lock) ^ on_main)}")
custom = {line.split("/")[2] for line in
          git("diff", "--name-only", "--ignore-cr-at-eol", "upstream", BRANCH, "--", FW).splitlines()}
grumpy = sorted(p.name for p in (ROOT / GR).iterdir() if p.is_dir())
order = [n for n in FIRST if n in lock] + sorted(n for n in lock if n not in FIRST)

out = []
w = out.append
count = 0


def gh(src, ref, dest, subpath=None, timeout=None, note=None):
    global count
    if count and count % BATCH == 0:
        w("  - action: waste_time # prevent github throttling\n    seconds: 10\n")
    count += 1
    w(f"  - action: download_github{'  # ' + note if note else ''}")
    w(f"    src: {src}")
    w(f"    ref: {ref}")
    if subpath:
        w(f"    subpath: {subpath}")
    w(f"    dest: {dest}")
    if timeout:
        w(f"    timeoutSeconds: {timeout}")
    w("")


def ours(subpath, dest, note=None):
    # every download of our repo fetches the whole zip (~45 MB) but only unpacks the subpath
    gh(REPO, BRANCH, dest, subpath=subpath, timeout=600, note=note)


w(f"""$engine: 3
$onesync: on
name: The Territories
version: {git('log', '-1', '--format=%cd', '--date=format:%Y.%m.%d', BRANCH).strip()}
author: Grumpy
description: |
  The Territories RedM server: RSG framework (pinned, with Territories customizations),
  grumpy-* scripts and the Territories NPC stores. Based on Rexshack's txAdminRecipe.

# GENERATED by tools/build-recipe.py - don't edit by hand, run the script.
# Stock RSG resources: Rexshack-RedM at the commit in upstream.lock.
# Customized RSG resources ({len(custom)}) and grumpy scripts ({len(grumpy)}): {REPO} ({BRANCH}).
tasks:
  # ================================================================ Base files
""")
ours("recipe", "./tmp/territories", note="server.cfg, logo, SQL")
import shutil
sql_dir = ROOT / "recipe" / "grumpy"
shutil.rmtree(sql_dir, ignore_errors=True)
sql_dir.mkdir(parents=True)
grumpy_sql = []
for name in grumpy:  # copies, so every database step runs up front under one connection
    src = ROOT / GR / name / "install.sql"
    if src.is_file():
        shutil.copyfile(src, sql_dir / f"{name}.sql")
        grumpy_sql.append(name)

w("""  - action: move_path
    src: ./tmp/territories/server.cfg
    dest: ./server.cfg

  - action: move_path
    src: ./tmp/territories/territories-logo.png
    dest: ./myLogo.png

  # ================================================================ Database
  # RSG's tables (RSG's recipe SQL, matching the pinned framework)
  - action: connect_database
  - action: query_database
    file: ./tmp/territories/rsg/rsgcore.sql
""")
w("  # grumpy tables (copies of each script's install.sql, all CREATE TABLE IF NOT EXISTS)")
for name in grumpy_sql:
    w(f"  - action: query_database\n    file: ./tmp/territories/grumpy/{name}.sql")
w("""  # base world setup from the dev server (tools/export-base-data.sh): NPC shops + templates, doors,
  # bartenders, hotels, back rooms, robbery, trader NPCs. Last, because it drops and refills those tables.
  # grumpy-gambling seeds its own default tables on first start (Config.DefaultTables).
  - action: query_database
    file: ./tmp/territories/territories_base.sql""")
w("""
  # ================================================================ Standalone
  - action: download_github
    src: https://github.com/citizenfx/cfx-server-data
    subpath: resources
    dest: ./resources/[cfx-default]
    timeoutSeconds: 600

  - action: download_file
    path: ./tmp/files/oxmysql.zip
    url: https://github.com/CommunityOx/oxmysql/releases/latest/download/oxmysql.zip
  - action: unzip
    src: ./tmp/files/oxmysql.zip
    dest: ./resources/[standalone]
""")
count = 2
for src, ref, dest in STANDALONE:
    gh(src, ref, dest)

w("  # ================================================================ RSG framework")
w(f"  # {len(lock) - len(custom)} stock (Rexshack-RedM, pinned) + {len(custom)} customized ({', '.join(sorted(custom))})\n")
for name in order:
    if name in custom:
        ours(f"{FW}/{name}", f"./resources/[framework]/{name}", note="customized")
    else:
        gh(f"https://github.com/Rexshack-RedM/{name}", lock[name], f"./resources/[framework]/{name}")

w("  # ================================================================ The Territories scripts\n")
for name in grumpy:
    ours(f"{GR}/{name}", f"./resources/[grumpy]/{name}")

w("  # ================================================================ Map mods\n")
for src, ref, dest in EXTRAS:
    gh(src, ref, dest)

w("""  # ================================================================ Clean up
  # rsg-chat replaces the cfx chat
  - action: remove_path
    path: ./resources/[cfx-default]/[gameplay]/chat

  - action: remove_path
    path: ./tmp
""")
(ROOT / "recipe" / "territories.yaml").write_text("\n".join(out), encoding="utf-8", newline="\n")
print(f"recipe/territories.yaml: {count} downloads ({len(lock) - len(custom)} stock RSG pinned, "
      f"{len(custom)} customized + {len(grumpy)} grumpy + 1 base from our repo)")
